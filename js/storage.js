/**
 * ReconTrace Case Management & Storage Layer
 * Manages investigation cases, evidence hashes, notes, leads, and dossier exports.
 */

class ReconStorage {
  static CASES_KEY = 'recontrace_active_cases';
  static ACTIVE_CASE_KEY = 'recontrace_current_case_id';

  /**
   * Get all stored cases
   */
  static async getAllCases() {
    try {
      if (typeof chrome !== 'undefined' && chrome.storage && chrome.storage.local) {
        const stored = await chrome.storage.local.get(this.CASES_KEY);
        return stored[this.CASES_KEY] || [];
      } else {
        const local = localStorage.getItem(this.CASES_KEY);
        return local ? JSON.parse(local) : [];
      }
    } catch (e) {
      console.warn('Failed to load cases:', e);
      return [];
    }
  }

  /**
   * Save cases array
   */
  static async saveAllCases(cases) {
    try {
      if (typeof chrome !== 'undefined' && chrome.storage && chrome.storage.local) {
        await chrome.storage.local.set({ [this.CASES_KEY]: cases });
      } else {
        localStorage.setItem(this.CASES_KEY, JSON.stringify(cases));
      }
      return true;
    } catch (e) {
      console.error('Failed to save cases:', e);
      return false;
    }
  }

  /**
   * Create or update a case
   */
  static async saveCase(caseData) {
    const cases = await this.getAllCases();
    const existingIndex = cases.findIndex(c => c.id === caseData.id);

    if (existingIndex >= 0) {
      cases[existingIndex] = { ...cases[existingIndex], ...caseData, updatedAt: new Date().toISOString() };
    } else {
      if (!caseData.id) caseData.id = 'case_' + Date.now();
      caseData.createdAt = new Date().toISOString();
      caseData.updatedAt = new Date().toISOString();
      if (!caseData.leads) caseData.leads = [];
      cases.unshift(caseData);
    }

    await this.saveAllCases(cases);
    return caseData;
  }

  /**
   * Add a verified lead to a case
   */
  static async addLeadToCase(caseId, lead) {
    const cases = await this.getAllCases();
    const currentCase = cases.find(c => c.id === caseId);
    if (!currentCase) return false;

    if (!currentCase.leads) currentCase.leads = [];
    // Avoid duplicate URLs
    const exists = currentCase.leads.some(l => l.url === lead.url);
    if (!exists) {
      lead.savedAt = new Date().toISOString();
      currentCase.leads.push(lead);
      await this.saveAllCases(cases);
    }
    return true;
  }

  /**
   * Export Case Dossier as formatted Markdown
   */
  static generateMarkdownDossier(caseData) {
    let md = `# 🛡️ RECONTRACE INVESTIGATION DOSSIER\n`;
    md += `**Case Title:** ${caseData.title || 'Untitled Case'}\n`;
    md += `**Case ID:** \`${caseData.id || 'N/A'}\`\n`;
    md += `**Created Date:** ${caseData.createdAt || 'N/A'}\n`;
    md += `**Evidence SHA-256 Hash:** \`${caseData.imageHash || 'N/A'}\`\n`;
    md += `**Investigator Notes:**\n> ${caseData.notes || 'No notes provided.'}\n\n`;

    md += `## 🎯 Verified Matches & Leads (${(caseData.leads || []).length} Recorded)\n\n`;

    if (!caseData.leads || caseData.leads.length === 0) {
      md += `*No leads flagged yet.*\n\n`;
    } else {
      caseData.leads.forEach((lead, i) => {
        md += `### Lead #${i + 1}: ${lead.source || 'Unknown Engine'} — **${lead.score}% Match**\n`;
        md += `- **URL:** ${lead.url}\n`;
        md += `- **Confidence:** ${lead.confidence?.label || 'N/A'}\n`;
        md += `- **Discovered At:** ${lead.savedAt || 'N/A'}\n`;
        if (lead.notes) md += `- **Notes:** ${lead.notes}\n`;
        md += `\n`;
      });
    }

    md += `---\n*Generated by ReconTrace Open-Source Humanitarian OSINT Suite*\n`;
    return md;
  }

  /**
   * Emergency Shredder: Purge all local cases, settings, and cache
   */
  static async emergencyWipeAllData() {
    try {
      if (typeof chrome !== 'undefined' && chrome.storage && chrome.storage.local) {
        await chrome.storage.local.clear();
      }
      localStorage.clear();
      sessionStorage.clear();
      return true;
    } catch (e) {
      console.error('Wipe failed:', e);
      return false;
    }
  }
}

if (typeof window !== 'undefined') {
  window.ReconStorage = ReconStorage;
}
